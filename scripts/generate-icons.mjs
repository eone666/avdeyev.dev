// Generates app/components/icons.tsx from @iconify-json/ri (Remix Icon), the
// same icon set react-icons/ri used to pull from. Add a name below and re-run
// `npm run icons`.
import { readFileSync, writeFileSync } from 'node:fs'

const ICONS = [
  'arrow-left-line',
  'award-line',
  'briefcase-2-line',
  'code-line',
  'download-2-line',
  'external-link-line',
  'facebook-line',
  'file-text-line',
  'github-line',
  'global-line',
  'graduation-cap-line',
  'instagram-line',
  'link',
  'linkedin-line',
  'mail-line',
  'map-pin-line',
  'reddit-line',
  'share-line',
  'telegram-2-line',
  'twitter-x-line',
  'user-3-line'
]

const set = JSON.parse(readFileSync('node_modules/@iconify-json/ri/icons.json', 'utf8'))

const componentName = (name) =>
  'Ri' + name.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('')

const lines = [
  '// GENERATED BY scripts/generate-icons.mjs — DO NOT EDIT BY HAND.',
  `// Source: @iconify-json/ri@${JSON.parse(readFileSync('node_modules/@iconify-json/ri/package.json', 'utf8')).version} (Remix Icon, Apache-2.0)`,
  "import { makeIcon } from './icon'",
  ''
]

/**
 * Pulls the single path out of an icon body.
 *
 * Only the `d` is kept, so the component can render a real <path> element
 * rather than injecting markup: raw HTML works when rendering on the server
 * but breaks in hono/jsx/dom, which is what islands hydrate with.
 */
const pathData = (name, body) => {
  const paths = [...body.matchAll(/<path\b[^>]*\bd="([^"]+)"[^>]*\/?>/g)]
  const elements = [...body.matchAll(/<[a-zA-Z]/g)]

  if (paths.length !== 1 || elements.length !== 1) {
    throw new Error(
      `icon "ri:${name}" is not a single <path>; makeIcon would need extending ` +
      `to render it. Body: ${body}`
    )
  }

  return paths[0][1]
}

for (const name of ICONS.slice().sort()) {
  const icon = set.icons[name]
  if (!icon) throw new Error(`icon "ri:${name}" not found in @iconify-json/ri`)

  const left = icon.left ?? set.left ?? 0
  const top = icon.top ?? set.top ?? 0
  const width = icon.width ?? set.width ?? 16
  const height = icon.height ?? set.height ?? 16

  lines.push(
    `export const ${componentName(name)} = makeIcon(`,
    `  '${left} ${top} ${width} ${height}',`,
    `  ${JSON.stringify(pathData(name, icon.body))}`,
    ')'
  )
}

writeFileSync('app/components/icons.tsx', lines.join('\n') + '\n')
console.log(`wrote app/components/icons.tsx (${ICONS.length} icons)`)
